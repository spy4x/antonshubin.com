#!/usr/bin/env -S deno run -N=raw.githubusercontent.com -R -W=components/tools/preact-components
/**
 * Writes `components/tools/preact-components/palette-index.ts`, the list the
 * search on /tools/preact-components runs over (#522): every export of kind
 * `component` in the pinned `@spy4x/preact-*` version's `llms.txt`, icons
 * apart, with the package, the `llms.txt` line and the live guide's card for
 * it when the guide has one. The line's markdown backticks are dropped: a
 * result row shows plain text, so they would show as written.
 *
 * Run it after bumping the pin in deno.json, then `deno fmt`:
 *   deno run -N=raw.githubusercontent.com -R -W=components/tools/preact-components scripts/palette-index.ts
 *
 * Idempotent: the same pin writes the same file.
 */
import config from "../deno.json" with { type: "json" }
import { catalogueSections, demoHref } from "@spy4x/preact-ui-guide"

const OUT = new URL(
  "../components/tools/preact-components/palette-index.ts",
  import.meta.url,
)

/** The pinned version, read off the `@spy4x/preact-ui` import. */
function pinnedVersion(): string {
  const spec = config.imports["@spy4x/preact-ui"]
  const version = spec.match(/@(\d+\.\d+\.\d+)$/)?.[1]
  if (!version) throw new Error(`no exact version in ${spec}`)
  return version
}

const version = pinnedVersion()
const url =
  `https://raw.githubusercontent.com/spy4x/preact-components/v${version}/llms.txt`
const response = await fetch(url)
if (!response.ok) throw new Error(`${url}: ${response.status}`)
const llms = await response.text()

const guide = new Map<string, string>()
for (const section of catalogueSections) {
  for (const name of section.names) {
    guide.set(name, demoHref(section.id, name))
  }
}

const entries = llms.split("\n")
  .map((line) => line.split("\t"))
  .filter(([, kind, from]) =>
    kind === "component" && from?.startsWith("@spy4x/preact-") &&
    from !== "@spy4x/preact-icons"
  )
  .map(([name, , from, line]) => ({
    name,
    from,
    line: line.trim().replaceAll("`", ""),
    ...(guide.has(name) ? { guide: guide.get(name) } : {}),
  }))
if (entries.length === 0) throw new Error(`${url} lists no component`)

await Deno.writeTextFile(
  OUT,
  `// Generated by scripts/palette-index.ts from @spy4x/preact-* ${version}'s
// llms.txt; rerun it after bumping the pin. Do not edit by hand.

/** One component the search on /tools/preact-components finds. */
export interface PaletteComponent {
  /** The export's name. */
  name: string
  /** The import specifier, \`@spy4x/preact-ui\` and so on. */
  from: string
  /** The library's one-line summary of it, as plain text. */
  line: string
  /** The live guide's card for it, a hash route, when the guide has one. */
  guide?: string
}

/** The library version this list was read from. */
export const PALETTE_VERSION = ${JSON.stringify(version)}

/** Every component the pinned version exports, icons apart, in llms.txt order. */
export const PALETTE_COMPONENTS: readonly PaletteComponent[] = ${
    JSON.stringify(entries, null, 2)
  }
`,
)
console.log(`${entries.length} components from ${version} → ${OUT.pathname}`)
