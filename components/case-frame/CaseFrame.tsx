/** A period as schema.org `temporalCoverage`: "2021", "2018/2019" or "2024/.." while ongoing. */
function temporalCoverage(period: Period): string {
  if (period.ongoing) return `${period.from}/..`
  if (period.to && period.to !== period.from) {
    return `${period.from}/${period.to}`
  }
  return `${period.from}`
}

/**
 * The project's JSON-LD node, from fields the `Project` record already holds
 * — no invented dates, ratings or facts. A `CreativeWork` (`#project`, which
 * `/work`'s `ItemList` points at) whose `author` and `creator` are the
 * site-wide Person and `isPartOf` the WebSite (#167). `image` lists the hero
 * screenshot first, then the rest, then the logo; `abstract` is the lead
 * (#246); `alternativeHeadline` is the `kind` line and `alternateName` the
 * product's other name (#523).
 *
 * No `Review` or `AggregateRating`: the reviews are the client's words on
 * Upwork, and self-served review markup is not eligible for rich results.
 * No `sourceOrganization`: `madeForName` is mostly a person, not an
 * organization, and typing it as one would invent a fact.
 */
export function projectJsonLd(project: Project, canonical: string) {
  const images = [
    ...projectScreenshots(project).map((s) =>
      `https://antonshubin.com${s.src}`
    ),
    ...(project.logoImageURL
      ? [`https://antonshubin.com${project.logoImageURL}`]
      : []),
  ]
  const sameAs = project.externalURL && !project.externalURLDead
    ? [project.externalURL]
    : undefined
  const person = { "@id": "https://antonshubin.com/#person" }

  return {
    "@context": "https://schema.org",
    "@type": "CreativeWork",
    "@id": `${canonical}#project`,
    "name": project.title,
    ...(project.alternateName
      ? { "alternateName": project.alternateName }
      : {}),
    ...(project.kind ? { "alternativeHeadline": project.kind } : {}),
    "description": project.description,
    "abstract": projectLead(project),
    "url": canonical,
    ...(images.length > 0 ? { "image": images } : {}),
    "author": person,
    "creator": person,
    "isPartOf": { "@id": "https://antonshubin.com/#website" },
    ...(project.tags && project.tags.length > 0
      ? { "keywords": project.tags.join(", ") }
      : {}),
    ...(sameAs ? { "sameAs": sameAs } : {}),
    ...(project.archived ? { "creativeWorkStatus": "Archived" } : {}),
    ...(project.period
      ? {
        "dateCreated": String(project.period.from),
        "temporalCoverage": temporalCoverage(project.period),
      }
      : {}),
    "mainEntityOfPage": { "@type": "WebPage", "@id": canonical },
  }
}

/** Sets the case page's head: the headline as `<title>`, the outcome-first description, the OG card. */
function setCaseHead(project: Project) {
  const slug = project.slug ?? ""
  head.value = {
    ...head.value,
    title: caseTitle(project),
    pageName: project.title,
    description: caseDescription(project),
    canonical: `https://antonshubin.com${workHref(slug)}`,
    ogType: "article",
    // 1200x630 PNG (#193), generated by `deno task og`: LinkedIn, X,
    // Facebook and Slack render no SVG link previews.
    ogImage: `https://antonshubin.com/img/og/projects/${slug}.png`,
    ogImageWidth: 1200,
    ogImageHeight: 630,
  }
}

/** Props of {@link CaseFrame}. */
export interface CaseFrameProps {
  project: Project
  /** `ctx.url.pathname`, for the nav's current item. */
  currentPath: string
  /**
   * Replaces the hero picture with the page's own first media, shown full
   * width under the title block (Sogroya's walkthrough).
   */
  hero?: ComponentChildren
  /**
   * Part 3, the page's own middle. Without it the default middle: the
   * strip of the other screenshots, then "What I built" (the 2014–2018
   * projects put the reviews between them) and the video.
   */
  children?: ComponentChildren
  /**
   * The page shows the client's reviews itself, in its hero or middle
   * (Corecircle's story, Connectful's reviews first), so the frame leaves
   * its own "What {client} said" out.
   */
  ownReviews?: boolean
}

/**
 * The shared frame of every `/work/<slug>` page (#523), like the tool
 * frame: the head and JSON-LD, the "‹ Work" back link, the hero (top line,
 * `<h1>` with the `kind` line, the outcome, one secondary link, the first
 * screenshot), the middle, the client's reviews, "How it is built" beside
 * the fact card, "More client work" and the closing band. Book appears in
 * the fact card and the band only. A custom page
 * (`routes/work/<slug>.tsx`) renders this with its own middle;
 * `routes/work/[slug].tsx` renders it for every other project.
 */
export function CaseFrame(
  { project, currentPath, hero, children, ownReviews = false }: CaseFrameProps,
) {
  setCaseHead(project)
  const slug = project.slug ?? ""
  const reviews = projectTestimonials(slug)
  const reviewsEl = <ProjectReviews project={project} reviews={reviews} />
  const inMiddle = children === undefined && reviewsFirst(project)
  const middle = children ?? (
    <>
      <CaseGallery project={project} />
      {inMiddle && reviewsEl}
      <WhatIBuilt project={project} />
      <CaseVideo project={project} />
    </>
  )
  return (
    <Layout currentPath={currentPath}>
      <SEOHead />
      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{
          __html: toJsonLd(projectJsonLd(project, head.value.canonical)),
        }}
      />
      <div class="max-w-6xl mx-auto">
        <Breadcrumb
          items={getBreadcrumb(head.value.canonical, project.title)}
        />
        <CaseHero project={project} media={hero} />
        <div data-case-middle class="mt-16 space-y-16">
          {middle}
          {!inMiddle && !ownReviews && reviewsEl}
          <CaseBuilt project={project} />
          <CaseMore related={relatedProjects(project)} />
        </div>
        <CaseBand project={project} review={reviews[0]} />
      </div>
    </Layout>
  )
}
